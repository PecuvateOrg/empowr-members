// Fixture integration test. Uses the repository's original private-booking
// schema/functions; the maintainer's current-schema dry run is also required.
import { PGlite } from '@electric-sql/pglite';
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const db = new PGlite();
try {
  await db.exec(`
    create role anon; create role authenticated; create role service_role bypassrls;
    create table mem_venues(id uuid primary key default gen_random_uuid());
    create table mem_accounts(id uuid primary key default gen_random_uuid());
    create table mem_participants(id uuid primary key, account_id uuid);
    create table mem_offerings(id uuid primary key default gen_random_uuid(), venue_id uuid);
    create table mem_occurrences(id uuid primary key default gen_random_uuid(), offering_id uuid, venue_id uuid, status text, starts_at timestamptz, ends_at timestamptz);
    create function mem_set_updated_at() returns trigger language plpgsql as $$begin new.updated_at=now(); return new; end;$$;
  `);
  const original = readFileSync(new URL('../../planning/architecture/private-bookings-schema.sql', import.meta.url), 'utf8');
  await db.exec(original.slice(0, original.indexOf('create function public.mem_block_private_slot')));
  await db.exec(readFileSync(new URL('../sql/members-private-offers.sql', import.meta.url), 'utf8'));
  const one = async (sql, args = []) => (await db.query(sql, args)).rows[0];
  const scalar = async (sql, args = []) => Object.values(await one(sql, args))[0];
  const venue = await scalar('insert into mem_venues default values returning id');
  const account = await scalar('insert into mem_accounts default values returning id');
  const other = await scalar('insert into mem_accounts default values returning id');
  const staff = '00000000-0000-4000-8000-000000000001';
  await db.query("insert into mem_private_booking_types(kind,title,unit_price_pence,min_places,max_places,venue_id,active) values('birthday','Party',2000,10,80,$1,true)", [venue]);
  const start = await scalar("select (((now() at time zone 'Europe/London')::date + (case when extract(isodow from now() at time zone 'Europe/London')::int = 6 then 7 else (6 - extract(isodow from now() at time zone 'Europe/London')::int + 7) % 7 end)) + time '15:00') at time zone 'Europe/London'");
  const create = (n = 10, at = start) => one('select * from mem_create_private_offer($1,$2,$3)', [at,n,staff]);
  const hold = (token, who = account) => one('select * from mem_hold_private_offer($1,$2)', [token,who]);
  const fails = (promise, code) => assert.rejects(promise, e => e.message.includes(code));
  const offer = await create();
  assert.equal(Date.parse(offer.expires_at) - Date.parse(offer.created_at), 48 * 3600000);
  assert.equal(await scalar('select count(*)::int from mem_private_bookings'), 0, 'creating an offer must not reserve a slot');
  const competing = await create();
  await fails(create(80), 'mem_private_above_maximum');
  await fails(create(9), 'mem_private_below_minimum');
  const far = new Date(Date.parse(start) + 21 * 86400000).toISOString();
  await fails(create(10, far), 'mem_private_offer_use_public');
  await fails(db.query("select * from mem_hold_private_booking($1,'birthday',$2,2,10)", [account,start]), 'mem_private_too_soon');
  await fails(hold('missing'), 'mem_private_offer_missing');
  await db.query("update mem_private_booking_types set unit_price_pence=3000 where kind='birthday'");
  const booking = await hold(offer.token);
  assert.equal(booking.price_pence, 20000, 'honour the quoted price');
  assert.equal(booking.status, 'pending_payment');
  assert.equal(booking.total_places, 11);
  assert.equal(booking.equipment_deadline_days, 7);
  assert.equal(booking.invite_token, null, 'no guest invitation before payment');
  assert.equal((await hold(offer.token)).id, booking.id, 'double click returns the same hold');
  await fails(hold(offer.token, other), 'mem_private_unavailable');
  await fails(hold(competing.token), 'mem_private_unavailable');
  await db.query("update mem_private_bookings set stripe_checkout_session_id='cs_offer_test' where id=$1", [booking.id]);
  const confirmed = await one("select * from mem_confirm_private_booking('cs_offer_test','pi_test')");
  assert.equal(confirmed.status, 'confirmed');
  assert.equal(confirmed.invite_token.length, 64);
  assert.equal((await db.query("select * from mem_confirm_private_booking('cs_offer_test','pi_test')")).rows.length, 0);
  await fails(hold(offer.token), 'mem_private_offer_used');
  await db.query("update mem_private_bookings set status='cancelled' where id=$1", [booking.id]);
  await db.query("update mem_private_offers set created_at=now()-interval '49 hours', expires_at=now()-interval '1 hour' where id=$1", [competing.id]);
  await fails(hold(competing.token), 'mem_private_offer_expired');
  const near = await create();
  await db.query("update mem_private_offers set created_at=now()-interval '47 hours 40 minutes', expires_at=now()+interval '20 minutes' where id=$1", [near.id]);
  await fails(hold(near.token), 'mem_private_offer_checkout_closed');
  const conflict = await create();
  const offering = await scalar('insert into mem_offerings(venue_id) values($1) returning id', [venue]);
  await db.query("insert into mem_occurrences(offering_id,status,starts_at,ends_at) values($1,'scheduled',$2,$2::timestamptz+interval '2 hours')", [offering,start]);
  await fails(hold(conflict.token), 'mem_private_session_clash');
  await fails(create(), 'mem_private_session_clash');
  assert.equal(await scalar("select has_table_privilege('anon','mem_private_offers','select')"), false);
  assert.equal(await scalar("select has_function_privilege('authenticated','mem_hold_private_offer(text,uuid)','execute')"), false);
  console.log('PASS private offer SQL: expiry, price snapshot, no offer hold, public cutoff, capacity, duplicate use, account binding, conflict, payment confirmation and grants');
} finally { await db.close(); }
